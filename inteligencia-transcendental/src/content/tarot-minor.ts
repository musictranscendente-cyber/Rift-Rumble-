export function minorName(suit: Suit, rank: number, lang: keyof L) {
  const r = RANKS[lang][rank - 1];
  const s = SUIT_NAMES[lang][suit];
  return lang === 'en' ? `${r} of ${s}` : `${r} de ${s}`;
}

